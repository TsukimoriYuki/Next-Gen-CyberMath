import type { Difficulty, Problem } from "@/lib/types";

const r = String.raw;

type GeometryProblemInput = {
  slug: string;
  title: string;
  unit: string;
  difficulty: Difficulty;
  tagline: string;
  statement: string;
  insight: string;
  hint: string;
  solution: string;
  tags: string[];
  relatedLessonSlug: string;
};

function makeGeometryProblem(input: GeometryProblemInput): Problem {
  return {
    slug: input.slug,
    title: input.title,
    unit: input.unit,
    difficulty: input.difficulty,
    tagline: input.tagline,
    hasGraph: false,
    statement: input.statement,
    relatedLessonSlug: input.relatedLessonSlug,
    tags: input.tags,
    steps: [
      {
        type: "INSIGHT",
        order: 0,
        title: "最初に見る条件",
        body: input.insight,
        relatedLessonSlug: input.relatedLessonSlug,
      },
      {
        type: "HINT",
        order: 1,
        title: "方針のヒント",
        body: input.hint,
      },
      {
        type: "SOLUTION",
        order: 2,
        title: "解答",
        body: input.solution,
      },
    ],
  };
}

