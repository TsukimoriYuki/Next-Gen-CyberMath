import type { Lecture, LectureBlock } from "@/data/specialLectures";

const r = String.raw;

type ShortcutTechnique = {
  id: string;
  title: string;
  what: string;
  condition: string;
  examUse: string;
  avoid: string;
  miniExample: string;
  orthodox: string;
  shortcut: string;
  accident: string;
};

function techniqueBlocks(chapterId: string, techniques: ShortcutTechnique[]): LectureBlock[] {
  return techniques.flatMap((technique): LectureBlock[] => [
    {
      id: `${chapterId}-${technique.id}-heading`,
      type: "heading",
      level: 3,
      text: technique.title,
    },
    {
      id: `${chapterId}-${technique.id}`,
      type: "callout",
      tone: "info",
      title: technique.title,
      text: r`**何をする技か**: ${technique.what}

**使える条件**: ${technique.condition}

**共通テストで刺さる場面**: ${technique.examUse}

**使ってはいけない条件**: ${technique.avoid}

**1問ミニ例題**: ${technique.miniExample}

**正攻法なら**: ${technique.orthodox}

**裏技なら**: ${technique.shortcut}

**事故例**: ${technique.accident}`,
    },
  ]);
}

